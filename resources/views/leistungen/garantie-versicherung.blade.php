(function() {
  var triggers = document.querySelectorAll('.garv-faq__trigger');

  triggers.forEach(function(trigger) {
    trigger.addEventListener('click', function() {
      var expanded = trigger.getAttribute('aria-expanded') === 'true';
      var panelId  = trigger.getAttribute('aria-controls');
      var panel    = document.getElementById(panelId);

      /* Alle schließen */
      triggers.forEach(function(t) {
        t.setAttribute('aria-expanded', 'false');
        var p = document.getElementById(t.getAttribute('aria-controls'));
        if (p) p.classList.remove('garv-faq__panel--open');
      });

      /* Aktuelles togglen */
      if (!expanded) {
        trigger.setAttribute('aria-expanded', 'true');
        if (panel) panel.classList.add('garv-faq__panel--open');
      }
    });
  });

  /* IntersectionObserver */
  var obs = new IntersectionObserver(function(entries) {
    entries.forEach(function(e) {
      if (e.isIntersecting) {
        e.target.classList.add('garv-faq__vis');
        obs.unobserve(e.target);
      }
    });
  }, { threshold: 0.06, rootMargin: '0px 0px -30px 0px' });
  document.querySelectorAll('.garv-faq__anim').forEach(function(el) {
    obs.observe(el);
  });
})();
