(function() {
  /* ── Intersection Observer for animations ── */
  var obs = new IntersectionObserver(function(entries) {
    entries.forEach(function(e) {
      if (e.isIntersecting) {
        e.target.classList.add('war-ba__vis');
        obs.unobserve(e.target);
      }
    });
  }, { threshold: 0.07, rootMargin: '0px 0px -30px 0px' });
  document.querySelectorAll('.war-ba__anim').forEach(function(el) {
    obs.observe(el);
  });

  /* ── Before/After Slider logic ── */
  function initSlider(wrap) {
    var afterWrap = wrap.querySelector('.war-ba__img-after-wrap');
    var divLine   = wrap.querySelector('.war-ba__divider-line');
    var handle    = wrap.querySelector('.war-ba__handle');
    var dragging  = false;

    function setPos(x) {
      var rect = wrap.getBoundingClientRect();
      var pct  = Math.min(Math.max((x - rect.left) / rect.width, 0.02), 0.98);
      var pctPx = (pct * 100).toFixed(2) + '%';
      afterWrap.style.width   = pctPx;
      divLine.style.left      = pctPx;
      handle.style.left       = pctPx;
    }

    /* Mouse */
    wrap.addEventListener('mousedown', function(e) {
      dragging = true;
      setPos(e.clientX);
      e.preventDefault();
    });
    document.addEventListener('mousemove', function(e) {
      if (!dragging) return;
      setPos(e.clientX);
    });
    document.addEventListener('mouseup', function() { dragging = false; });

    /* Touch */
    wrap.addEventListener('touchstart', function(e) {
      dragging = true;
      setPos(e.touches[0].clientX);
    }, { passive: true });
    wrap.addEventListener('touchmove', function(e) {
      if (!dragging) return;
      setPos(e.touches[0].clientX);
    }, { passive: true });
    wrap.addEventListener('touchend', function() { dragging = false; });
  }

  document.querySelectorAll('.war-ba__slider-wrap').forEach(function(wrap) {
    initSlider(wrap);
  });
})();
