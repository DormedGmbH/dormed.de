<script>
(function() {
  /* ── IntersectionObserver ── */
  var obs = new IntersectionObserver(function(entries) {
    entries.forEach(function(e) {
      if (e.isIntersecting) {
        e.target.classList.add('war-faq__vis');
        obs.unobserve(e.target);
      }
    });
  }, { threshold: 0.07, rootMargin: '0px 0px -30px 0px' });
  document.querySelectorAll('.war-faq__anim').forEach(function(el) {
    obs.observe(el);
  });

  /* ── Accordion ── */
  document.querySelectorAll('.war-faq__btn').forEach(function(btn) {
    btn.addEventListener('click', function() {
      var item   = btn.closest('.war-faq__item');
      var panel  = document.getElementById(btn.getAttribute('aria-controls'));
      var isOpen = item.classList.contains('war-faq__item--open');

      /* Close all others */
      document.querySelectorAll('.war-faq__item--open').forEach(function(openItem) {
        openItem.classList.remove('war-faq__item--open');
        openItem.querySelector('.war-faq__btn').setAttribute('aria-expanded', 'false');
        openItem.querySelector('.war-faq__panel').style.maxHeight = '0';
      });

      /* Toggle clicked */
      if (!isOpen) {
        item.classList.add('war-faq__item--open');
        btn.setAttribute('aria-expanded', 'true');
        panel.style.maxHeight = panel.scrollHeight + 'px';
      }
    });
  });
})();
