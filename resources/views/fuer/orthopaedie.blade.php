        <div class="or-faq__answer" role="region">
          <div class="or-faq__answer-inner"><p class="or-faq__answer-text"><strong>Anisotropie</strong> ist ein spezifisches Artefakt der MSK-Sonographie: Sehnen erscheinen nur dann echogen (hell) wenn der Schallkopf exakt senkrecht zur Sehnenstruktur ausgerichtet ist. Bei leichter Abwinkelung erscheint die gleiche Sehne hypoechogen (dunkel) — was fälschlicherweise als Riss oder Tendinopathie interpretiert werden kann. Die Anisotropie ist kein Geräteproblem, sondern eine physikalische Eigenschaft — sie erfordert Erfahrung und korrektes Schallkopfhandling. Einige moderne Geräte bieten Kompensationsalgorithmen. DEGUM-Kurse für MSK thematisieren Anisotropie systematisch.</p></div>
