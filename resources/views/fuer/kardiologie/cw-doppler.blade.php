        <h2 class="cwd-b2__h2 cwd-b2__anim cwd-b2__anim--d1">Bernoulli-Gleichung — Druckgradient aus Jetgeschwindigkeit berechnen</h2>

        <p class="cwd-b2__p cwd-b2__anim cwd-b2__anim--d2">
          Die wichtigste klinische Stärke des CW-Dopplers liegt in der <strong>nicht-invasiven Druckgradient-Messung</strong>. Mit der vereinfachten Bernoulli-Gleichung lässt sich aus der gemessenen Maximalgeschwindigkeit direkt der Druckunterschied über einer Herzklappe berechnen — eine Information, für die früher ein Herzkatheter nötig war. (<a href="https://ekgecho.de/thema/das-bernoulli-prinzip-und-die-messungen-von-druckgradienten/" target="_blank" rel="noopener noreferrer" style="color:rgb(9,58,126)">Bernoulli-Prinzip in der Echokardiographie — ekgecho.de</a>)
        </p>

        <!-- Formel-Box -->
        <div class="cwd-b2__formula-box cwd-b2__anim cwd-b2__anim--d2">
          <div class="cwd-b2__formula-head">
            <div class="cwd-b2__formula-head-label">Vereinfachte Bernoulli-Gleichung</div>
          </div>
          <div class="cwd-b2__formula-body">
            <div class="cwd-b2__formula-eq" role="img" aria-label="Druckgradient Delta P gleich 4 mal v hoch 2">
              <span class="eq-hl">ΔP</span>
              <span style="color:rgb(90,110,140); font-weight:400">=</span>
              <span>4</span>
              <span style="color:rgb(90,110,140); font-weight:400">×</span>
              <span class="eq-hl">v²</span>
            </div>
            <div class="cwd-b2__formula-legend">
              <div class="cwd-b2__formula-legend-item">
                <span class="cwd-b2__formula-legend-key">ΔP</span>
                <span>Druckgradient in <strong>mmHg</strong> — Druckunterschied zwischen den zwei Seiten der Klappe</span>
              </div>
              <div class="cwd-b2__formula-legend-item">
                <span class="cwd-b2__formula-legend-key">4</span>
                <span>Konstante — vereinfachte Näherung aus Blutdichte und Umrechnungsfaktor</span>
              </div>
              <div class="cwd-b2__formula-legend-item">
                <span class="cwd-b2__formula-legend-key">v</span>
                <span>Maximale Jetgeschwindigkeit in <strong>m/s</strong> — gemessen mit CW-Doppler (Vmax)</span>
              </div>
            </div>
          </div>
        </div>

        <p class="cwd-b2__p cwd-b2__anim cwd-b2__anim--d2">
          Die Formel gilt, weil an einer Klappenöffnung die proximale Geschwindigkeit (v1 im LVOT, typisch ca. 1 m/s) im Verhältnis zur distalen Jetgeschwindigkeit (v2 an der Stenose, oft 3–5 m/s) vernachlässigbar klein ist — durch das Quadrieren der Werte wird dieser Unterschied noch größer. Die vollständige Bernoulli-Gleichung lautet ΔP = 4(v2² − v1²), vereinfacht auf ΔP = 4v² wenn v1 &lt; 1,5 m/s.
        </p>

