              <span class="cwd-b4__limits-dash" aria-hidden="true"></span>
              <span><strong>Winkelsensitivität:</strong> Die Bernoulli-Gleichung liefert nur bei Winkeln &lt; 15° zur Flussrichtung korrekte Werte. Winkelfehler führen systematisch zur Unterschätzung der Jetgeschwindigkeit und des Druckgradienten.</span>
            </li>
