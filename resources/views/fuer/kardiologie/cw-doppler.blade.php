            <li class="cwd-b4__limits-item">
              <span class="cwd-b4__limits-dash" aria-hidden="true"></span>
              <span><strong>Kein anatomisches Bild:</strong> Der reine CW-Doppler (Stiftsonde) liefert kein B-Bild. Für eine vollständige Diagnostik ist die Kombination mit B-Bild und <a href="/blog/kardiologie/farbduplex/" style="color:rgb(9,58,126)">Farbdoppler</a> unerlässlich.</span>
