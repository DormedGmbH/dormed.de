(function () {
  'use strict';

  var aside       = document.getElementById('cwd-b4-aside');
  var placeholder = document.getElementById('cwd-b4-placeholder');
  var inner       = document.getElementById('cwd-b4-inner');
  if (!aside || !placeholder || !inner) return;

  var stickyStartY = null;
  var asideLeft    = null;
  var asideWidth   = null;
  var BOTTOM_PAD   = 40;

  function getNavHeight() {
    var nav = document.querySelector('.nav__wrap') || document.querySelector('nav');
    return nav ? nav.getBoundingClientRect().height : 68;
  }
  function isMobile() { return window.innerWidth <= 1100; }

  function measure() {
    if (isMobile()) return;
    aside.classList.remove('cwd-b4__aside--fixed');
    aside.style.position = aside.style.top = aside.style.left = aside.style.width = '';
    placeholder.classList.remove('cwd-b4__aside-placeholder--active');
    placeholder.style.height = '';
    var navH = getNavHeight();
    var rect = aside.getBoundingClientRect();
    asideLeft    = rect.left;
    asideWidth   = rect.width;
    stickyStartY = rect.top + window.scrollY - navH - 20;
  }

  function update() {
    if (isMobile()) {
      aside.classList.remove('cwd-b4__aside--fixed');
      aside.style.position = aside.style.top = aside.style.left = aside.style.width = '';
      placeholder.classList.remove('cwd-b4__aside-placeholder--active');
      return;
    }
    if (stickyStartY === null) { measure(); }

    var navH    = getNavHeight();
    var scrollY = window.scrollY;
    var asideH  = aside.offsetHeight;
    var innerH  = inner.offsetHeight;

    if (scrollY < stickyStartY) {
      aside.classList.remove('cwd-b4__aside--fixed');
      aside.style.position = aside.style.top = aside.style.left = aside.style.width = '';
      placeholder.classList.remove('cwd-b4__aside-placeholder--active');
      placeholder.style.height = '';
      return;
    }

    placeholder.classList.add('cwd-b4__aside-placeholder--active');
    placeholder.style.height = asideH + 'px';

    var innerRect       = inner.getBoundingClientRect();
    var sidebarWouldEnd = navH + 20 + asideH;

    if (innerRect.bottom - BOTTOM_PAD <= sidebarWouldEnd) {
      var relLeft = asideLeft - innerRect.left;
      var maxTop  = Math.max(0, innerH - asideH - BOTTOM_PAD);
      aside.classList.remove('cwd-b4__aside--fixed');
      aside.style.position = 'absolute';
      aside.style.top      = maxTop + 'px';
      aside.style.left     = relLeft + 'px';
      aside.style.width    = asideWidth + 'px';
    } else {
      aside.classList.add('cwd-b4__aside--fixed');
      aside.style.position = '';
      aside.style.top      = (navH + 20) + 'px';
      aside.style.left     = asideLeft + 'px';
      aside.style.width    = asideWidth + 'px';
    }
  }

  window.addEventListener('scroll', update, { passive: true });
  window.addEventListener('resize', function () {
    stickyStartY = null; asideLeft = null;
    setTimeout(update, 60);
  }, { passive: true });
  setTimeout(function () { measure(); update(); }, 250);

