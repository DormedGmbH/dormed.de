        <h2 class="pwd-b1__h2 pwd-b1__anim pwd-b1__anim--d1">Was ist ein PW-Doppler?</h2>

        <div class="pwd-b1__keybox pwd-b1__anim pwd-b1__anim--d2">
          <div class="pwd-b1__keybox-label">Kurzdefinition</div>
          <p class="pwd-b1__keybox-text">
            Der <strong>Pulsed-Wave-Doppler (PW-Doppler)</strong> — zu Deutsch <em>gepulster Doppler-Ultraschall</em> — ist ein spezielles Ultraschallverfahren zur präzisen Messung von Blutflussgeschwindigkeiten an einem <strong>definierten Ort</strong> im Körper. Es findet vor allem in der <strong>Herz- und Gefäßdiagnostik</strong> breite Anwendung.
          </p>
        </div>

        <p class="pwd-b1__p pwd-b1__anim pwd-b1__anim--d2">
          Ein PW-Doppler-Ultraschall sendet kurze Schallpulse aus und empfängt die Echos mit demselben Schallkopf — ein einzelner piezoelektrischer Kristall wechselt zwischen Senden und Empfangen. Aus der Laufzeit der Echos bestimmt das Gerät eine exakte Tiefe im Gewebe, die als Messort dient. Man spricht auch von einem <strong>Sample Volume</strong> (Messvolumen), das entlang des Ultraschallstrahls frei wählbar ist.
        </p>

        <div class="pwd-b1__sv-cards pwd-b1__anim pwd-b1__anim--d2">
