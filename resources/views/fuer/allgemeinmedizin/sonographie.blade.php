        <div class="blog-body3__anim blog-body3__anim--d2">
          <h3 class="blog-body3__h3"><span class="blog-body3__h3-marker" aria-hidden="true"></span>Wie läuft eine Sonographie ab?</h3>
        </div>
        <p class="blog-body3__p blog-body3__anim blog-body3__anim--d2">Der Prozess beginnt bereits vor der eigentlichen Untersuchung — und ist für den Patienten unkompliziert und stressfrei.</p>

        <div class="blog-body3__timeline blog-body3__anim blog-body3__anim--d2">
          <div class="blog-body3__tl-step"><div class="blog-body3__tl-num" aria-hidden="true">01</div><div class="blog-body3__tl-body"><div class="blog-body3__tl-title">Vorbereitung</div><div class="blog-body3__tl-text">Je nach Anweisung des Arztes nüchtern bleiben oder eine volle Blase haben — um optimale Bilder zu gewährleisten. Der behandelnde Arzt informiert genau darüber, was zu beachten ist.</div></div></div>
          <div class="blog-body3__tl-step"><div class="blog-body3__tl-num" aria-hidden="true">02</div><div class="blog-body3__tl-body"><div class="blog-body3__tl-title">Ankunft &amp; Freilegen des Untersuchungsbereichs</div><div class="blog-body3__tl-text">Nach Ankunft in der Praxis wird der zu untersuchende Bereich freigelegt. Oft genügt es, nur einen Teil der Kleidung zu entfernen.</div></div></div>
          <div class="blog-body3__tl-step"><div class="blog-body3__tl-num" aria-hidden="true">03</div><div class="blog-body3__tl-body"><div class="blog-body3__tl-title">Auftragen des Ultraschallgels</div><div class="blog-body3__tl-text">Ein spezielles Gel verbessert die Leitfähigkeit der Schallwellen und verhindert störende Luftblasen zwischen Haut und Schallkopf. Es ist angenehm temperiert und lässt sich nach der Untersuchung leicht entfernen.</div></div></div>
          <div class="blog-body3__tl-step"><div class="blog-body3__tl-num" aria-hidden="true">04</div><div class="blog-body3__tl-body"><div class="blog-body3__tl-title">Durchführung der Untersuchung</div><div class="blog-body3__tl-text">Der Arzt führt den Ultraschallkopf sanft über den Untersuchungsbereich — und positioniert ihn in verschiedene Winkel, um detaillierte Bilder aus unterschiedlichen Perspektiven zu erhalten. Der Vorgang ist <strong>schmerzfrei</strong>. Bei speziellen Untersuchungen wie der frühen Schwangerschaftsdiagnostik kann die Sonographie auch transvaginal durchgeführt werden.</div></div></div>
          <div class="blog-body3__tl-step"><div class="blog-body3__tl-num" aria-hidden="true">05</div><div class="blog-body3__tl-body"><div class="blog-body3__tl-title">Bildanalyse in Echtzeit</div><div class="blog-body3__tl-text">Während der Untersuchung betrachtet der Arzt die Bilder auf einem Monitor. Er kann Bereiche vergrößern oder strukturelle Auffälligkeiten sofort erkennen. In manchen Fällen kommentiert er die Bilder direkt.</div></div></div>
          <div class="blog-body3__tl-step"><div class="blog-body3__tl-num" aria-hidden="true">06</div><div class="blog-body3__tl-body"><div class="blog-body3__tl-title">Abschluss der Untersuchung</div><div class="blog-body3__tl-text">Das Gel wird entfernt, der Patient kann sich sofort wieder anziehen und seinen normalen Aktivitäten nachgehen. Die gesamte Untersuchung dauert in der Regel <strong>nicht länger als 30 Minuten</strong>.</div></div></div>
          <div class="blog-body3__tl-step"><div class="blog-body3__tl-num" aria-hidden="true">07</div><div class="blog-body3__tl-body"><div class="blog-body3__tl-title">Befundbesprechung</div><div class="blog-body3__tl-text">Häufig gibt es bereits unmittelbar nach der Untersuchung erste Informationen zu den Ergebnissen. Eine detaillierte Auswertung erfolgt anschließend — falls notwendig, werden weitere Schritte oder Nachuntersuchungen geplant.</div></div></div>
