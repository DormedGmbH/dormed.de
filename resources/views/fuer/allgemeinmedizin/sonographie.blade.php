  /* Auf-/Zuklappen */
  var toggle = document.getElementById('toc-toggle');
  var body   = document.getElementById('toc-body');
  var chev   = document.getElementById('toc-chevron');
  var isOpen = true;
  if (toggle && body && chev) {
    chev.classList.add('blog-toc__chevron--open');
    toggle.addEventListener('click', function() {
      isOpen = !isOpen;
      body.classList.toggle('blog-toc__body--closed', !isOpen);
      chev.classList.toggle('blog-toc__chevron--open', isOpen);
    });
  }

  /* Smooth Scroll */
  document.querySelectorAll('.blog-toc__item').forEach(function(link) {
    link.addEventListener('click', function(e) {
      var href = link.getAttribute('href');
      if (!href || href.charAt(0) !== '#') return;
      var target = document.querySelector(href);
      if (!target) return;
      e.preventDefault();
      window.scrollTo({ top: target.getBoundingClientRect().top + window.scrollY - 90, behavior: 'smooth' });
    });
  });

  /* Lesefortschritt */
  var bar = document.getElementById('toc-progress');
