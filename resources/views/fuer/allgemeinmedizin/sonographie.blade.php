        </div>
        <p class="blog-body2__p blog-body2__anim blog-body2__anim--d2">
          Die Sonographie basiert auf dem <strong>Echoprinzip</strong>. Stellen Sie sich vor, Sie rufen in eine Schlucht hinein und hören das Echo Ihrer Stimme zurück. Ähnlich verhält es sich hier — nur dass hochfrequente Schallwellen verwendet werden, um ein Bild des Körperinneren zu erzeugen.
        </p>

        <div class="blog-body2__steps blog-body2__anim blog-body2__anim--d2">
          <div class="blog-body2__step">
            <div class="blog-body2__step-num" aria-hidden="true">01</div>
            <div class="blog-body2__step-body">
              <div class="blog-body2__step-title">Aussenden der Schallwellen</div>
              <div class="blog-body2__step-text">Der Ultraschallkopf — auch <em>Transducer</em> genannt — sendet Schallwellen in den Körper aus. Diese Wellen sind für das menschliche Ohr nicht hörbar: Sie bewegen sich in einem Frequenzbereich zwischen <strong>2 und 30 MHz</strong>. In der Dermatologie kommen sogar ultrahochfrequente Linearsonden bis zu <strong>70 MHz</strong> zum Einsatz.</div>
            </div>
          </div>
          <div class="blog-body2__step">
            <div class="blog-body2__step-num" aria-hidden="true">02</div>
            <div class="blog-body2__step-body">
              <div class="blog-body2__step-title">Reflexion im Gewebe</div>
              <div class="blog-body2__step-text">Die Schallwellen treffen auf verschiedene Gewebearten und Strukturen — Muskeln, Organe, Flüssigkeiten. Jedes Gewebe reflektiert sie unterschiedlich, abhängig von <strong>Dichte</strong> und <strong>Zusammensetzung</strong>. Knochen und Luft reflektieren stark, Flüssigkeiten lassen die Wellen nahezu ungehindert passieren.</div>
            </div>
          </div>
          <div class="blog-body2__step">
            <div class="blog-body2__step-num" aria-hidden="true">03</div>
            <div class="blog-body2__step-body">
              <div class="blog-body2__step-title">Empfang der Echos</div>
              <div class="blog-body2__step-text">Die reflektierten Schallwellen — die Echos — werden vom Transducer wieder aufgenommen. Die Dauer des Hin- und Rückwegs gibt Aufschluss über die <strong>Tiefe</strong> der jeweiligen Struktur.</div>
            </div>
          </div>
          <div class="blog-body2__step">
            <div class="blog-body2__step-num" aria-hidden="true">04</div>
            <div class="blog-body2__step-body">
              <div class="blog-body2__step-title">Bildentstehung — das Sonogramm</div>
              <div class="blog-body2__step-text">Die empfangenen Signale werden in Echtzeit in ein visuelles Bild umgewandelt. Auf dem <strong>Sonogramm</strong> erscheinen feste Strukturen wie Knochen hell (<em>hyperechogen</em>), während Flüssigkeiten dunkel (<em>anechogen</em>) dargestellt werden.</div>
            </div>
