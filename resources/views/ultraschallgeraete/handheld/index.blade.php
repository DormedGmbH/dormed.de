    const href = link.getAttribute('href');
    if (href === '#' || href.length < 2) return;

    const targetEl = document.querySelector(href);
    if (!targetEl) return; 

    e.preventDefault();
    smoothScrollTo(href);
    
    if (history.pushState) {
      history.pushState(null, null, href);
