  function measureStickyStartY() {
    sidebar.classList.remove('ug-grid__sidebar--fixed');
    sidebar.style.position = '';
    sidebar.style.top  = '';
    sidebar.style.left = '';
    if (placeholder) placeholder.classList.remove('ug-grid__sidebar-placeholder--active');
    var navH = getNavHeight();
    var rect = sidebar.getBoundingClientRect();
    sidebarLeft  = rect.left;
    stickyStartY = rect.top + window.scrollY - navH - 20;
    if (window.scrollY >= stickyStartY) {
      if (placeholder) placeholder.classList.add('ug-grid__sidebar-placeholder--active');
      sidebar.classList.add('ug-grid__sidebar--fixed');
      sidebar.style.left = sidebarLeft + 'px';
    }
  }

  function updateSidebarPos() {
    if (!sidebar || !outer) return;
    if (stickyStartY === null) { measureStickyStartY(); return; }
    var navH      = getNavHeight();
    var scrollY   = window.scrollY;
    var sidebarH  = sidebar.offsetHeight;
    var outerH    = outer.offsetHeight;
    var maxAbsTop = outerH - sidebarH - bottomPad;
    if (scrollY < stickyStartY) {
      if (placeholder) placeholder.classList.remove('ug-grid__sidebar-placeholder--active');
      sidebar.classList.remove('ug-grid__sidebar--fixed');
      sidebar.style.position = '';
      sidebar.style.top  = '';
