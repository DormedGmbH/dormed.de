(function() {
  'use strict';

  /* ═══════════════════════════════════════════
     1. SCROLL-ANIMATIONEN
     ═══════════════════════════════════════════ */
  var obs = new IntersectionObserver(function(entries) {
    entries.forEach(function(e) {
      if (e.isIntersecting) {
        e.target.classList.add('kon-form__vis');
        obs.unobserve(e.target);
      }
    });
  }, { threshold: 0.06, rootMargin: '0px 0px -40px 0px' });
  ['kon-left','kon-right'].forEach(function(id) {
    var el = document.getElementById(id);
    if (el) obs.observe(el);
  });

  /* ═══════════════════════════════════════════
     2. SELECT PLACEHOLDER
     ═══════════════════════════════════════════ */
  var selects = document.querySelectorAll('.kon-form__select');
  selects.forEach(function(sel) {
    function update() {
      if (sel.value === '') sel.classList.add('kon-form__select--placeholder');
      else sel.classList.remove('kon-form__select--placeholder');
    }
    update();
    sel.addEventListener('change', update);
  });

  /* ═══════════════════════════════════════════
     3. EXPANDER TOGGLE (mit ARIA)
     ═══════════════════════════════════════════ */
  var expandBtn   = document.getElementById('kon-expand-btn');
  var expandPanel = document.getElementById('kon-expand-panel');
  if (expandBtn && expandPanel) {
    expandBtn.addEventListener('click', function() {
      var isOpen = expandPanel.classList.contains('kon-form__expand-panel--open');
      if (isOpen) {
        expandPanel.classList.remove('kon-form__expand-panel--open');
        expandBtn.classList.remove('kon-form__expand-toggle--open');
        expandBtn.setAttribute('aria-expanded', 'false');
        expandPanel.setAttribute('aria-hidden', 'true');
      } else {
        expandPanel.classList.add('kon-form__expand-panel--open');
        expandBtn.classList.add('kon-form__expand-toggle--open');
        expandBtn.setAttribute('aria-expanded', 'true');
        expandPanel.setAttribute('aria-hidden', 'false');
      }
    });
  }

  /* ═══════════════════════════════════════════
     4. RÜCKRUF-DATUM-LOGIK
     ═══════════════════════════════════════════ */
  var rueckrufCheck = document.getElementById('kon-rueckruf');
  var callbackEl    = document.getElementById('kon-callback');
  var datumEl       = document.getElementById('kon-rueckruf-datum');

  function nextWeekday(d) {
    var day = d.getDay();
    if (day === 6) d.setDate(d.getDate() + 2);
    if (day === 0) d.setDate(d.getDate() + 1);
    return d;
  }
  function toDateStr(d) {
    var y = d.getFullYear();
    var m = String(d.getMonth() + 1).padStart(2, '0');
    var dd = String(d.getDate()).padStart(2, '0');
    return y + '-' + m + '-' + dd;
  }
  function isWeekend(dateStr) {
    var d = new Date(dateStr + 'T00:00:00');
    return d.getDay() === 0 || d.getDay() === 6;
  }

  if (rueckrufCheck && callbackEl && datumEl) {
    var tomorrow = new Date();
    tomorrow.setDate(tomorrow.getDate() + 1);
    var minDate = nextWeekday(tomorrow);
    datumEl.min = toDateStr(minDate);
    datumEl.value = toDateStr(minDate);

    datumEl.addEventListener('change', function() {
      if (isWeekend(datumEl.value)) {
        var d = new Date(datumEl.value + 'T00:00:00');
        datumEl.value = toDateStr(nextWeekday(d));
      }
    });

    rueckrufCheck.addEventListener('change', function() {
      var telefonLabel = document.getElementById('kon-telefon-label');
      var telefonHint  = document.getElementById('kon-telefon-hint');
      var telefonInput = document.getElementById('kon-telefon');

      if (rueckrufCheck.checked) {
        callbackEl.classList.add('kon-form__callback--vis');
        // Telefon wird Pflicht
        if (telefonLabel) telefonLabel.classList.add('kon-form__label--req');
        if (telefonHint)  telefonHint.style.display = 'none';
        if (telefonInput) telefonInput.required = true;
      } else {
        callbackEl.classList.remove('kon-form__callback--vis');
        // Telefon wieder optional
        if (telefonLabel) telefonLabel.classList.remove('kon-form__label--req');
        if (telefonHint)  telefonHint.style.display = '';
        if (telefonInput) {
          telefonInput.required = false;
          telefonInput.removeAttribute('aria-invalid');
        }
      }
    });
  }

  /* ═══════════════════════════════════════════
     5. PLZ-VALIDATION (Live-Input)
     ═══════════════════════════════════════════ */
  var plzInput = document.getElementById('kon-plz');
  if (plzInput) {
    plzInput.addEventListener('input', function() {
      this.value = this.value.replace(/[^0-9]/g, '');
      if (this.value.length === 5 && this.getAttribute('aria-invalid') === 'true') {
        this.removeAttribute('aria-invalid');
      }
    });
  }

  // Live-Clearing für Telefon bei Rückruf-Fehler
  var telefonInputLive = document.getElementById('kon-telefon');
  if (telefonInputLive) {
    telefonInputLive.addEventListener('input', function() {
      if (this.value.trim() && this.getAttribute('aria-invalid') === 'true') {
        this.removeAttribute('aria-invalid');
      }
    });
  }

  // ★★★ Generelles Live-Clearing für alle Form-Inputs (Name, E-Mail, etc.)
  // Entfernt aria-invalid sobald User in einem fehlerhaften Feld tippt
  var formForLive = document.getElementById('kon-form');
  if (formForLive) {
    formForLive.addEventListener('input', function(e) {
      var t = e.target;
      if (!t || !t.matches) return;
      if (t.matches('input, textarea, select') && t.getAttribute('aria-invalid') === 'true') {
        // Nur entfernen wenn das Feld jetzt valide aussieht
        var val = (t.value || '').trim();
        if (val) t.removeAttribute('aria-invalid');
      }
    });
    // Checkboxen feuern 'change', nicht 'input'
    formForLive.addEventListener('change', function(e) {
      var t = e.target;
      if (!t || !t.matches) return;
      if (t.matches('input[type="checkbox"]') && t.checked && t.getAttribute('aria-invalid') === 'true') {
        t.removeAttribute('aria-invalid');
      }
    });
  }

  /* ═══════════════════════════════════════════
     6. KONSOLIDIERTE VALIDATION
     Sammelt alle Fehler gleichzeitig statt sequentiell
     ═══════════════════════════════════════════ */
  function clearFieldErrors() {
    var form = document.getElementById('kon-form');
    if (!form) return;
    form.querySelectorAll('[aria-invalid="true"]').forEach(function(el) {
      el.removeAttribute('aria-invalid');
    });
  }

  // Feld-spezifische Labels für Fehlermeldungen
  var FIELD_LABELS = {
    'name':    'Bitte geben Sie Ihren Namen an.',
    'email':   'Bitte geben Sie Ihre E-Mail-Adresse an.',
    'telefon': 'Bitte geben Sie Ihre Telefonnummer an.',
    'plz':     'Bitte geben Sie Ihre Postleitzahl an.'
  };

  // Einfache E-Mail-Format-Prüfung (ergänzend zur HTML5-type=email)
  function isValidEmail(val) {
    if (!val) return false;
    return /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(val.trim());
  }

  function validateForm() {
    var errors = [];
    var firstInvalidEl = null;

    var form = document.getElementById('kon-form');
    if (!form) return { errors: errors, firstInvalidEl: null };

    clearFieldErrors();

    // ★★★ Alle required-Felder durchgehen — auch Name, E-Mail, etc.
    var requiredFields = form.querySelectorAll('input[required], textarea[required], select[required]');
    requiredFields.forEach(function(field) {
      var name  = field.name;
      var type  = field.type;
      var value = (field.value || '').trim();

      // Checkboxen: muss gecheckt sein
      if (type === 'checkbox') {
        if (!field.checked) {
          if (name === 'datenschutz') {
            errors.push('Bitte stimmen Sie der Datenschutzerklärung zu.');
          } else {
            errors.push('Bitte bestätigen Sie das erforderliche Feld.');
          }
          field.setAttribute('aria-invalid', 'true');
          if (!firstInvalidEl) firstInvalidEl = field;
        }
        return;
      }

      // Leeres Feld
      if (!value) {
        var msg = FIELD_LABELS[name] || 'Bitte füllen Sie alle Pflichtfelder aus.';
        errors.push(msg);
        field.setAttribute('aria-invalid', 'true');
        if (!firstInvalidEl) firstInvalidEl = field;
        return;
      }

      // Format-spezifische Checks
      if (type === 'email' && !isValidEmail(value)) {
        errors.push('Bitte geben Sie eine gültige E-Mail-Adresse an.');
        field.setAttribute('aria-invalid', 'true');
        if (!firstInvalidEl) firstInvalidEl = field;
        return;
      }

      if (name === 'plz' && value.length !== 5) {
        errors.push('Bitte geben Sie eine gültige 5-stellige PLZ an — so können wir Ihre Anfrage an den nächsten Standort weiterleiten.');
        field.setAttribute('aria-invalid', 'true');
        if (!firstInvalidEl) firstInvalidEl = field;
        return;
      }
    });

    // ★★★ Rückruf-Check: Telefon wird required wenn Rückruf gechecked,
    // aber das required-Attribut wird dynamisch gesetzt — also ist es
    // im Loop oben bereits abgedeckt. Hier nur noch das Expander-Panel öffnen
    // falls der Telefon-Fehler bei aktiviertem Rückruf auftritt.
